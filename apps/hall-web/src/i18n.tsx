export const DICTIONARIES: Record<Locale, Partial<Record<Key, string>>> = { 'pt-BR': ptBR, en };

export function translate(locale: Locale, key: Key, vars: Record<string, string | number> = {}): string {
  const text = DICTIONARIES[locale][key] ?? ptBR[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

const STORAGE_KEY = 'hall.locale';

function initialLocale(): Locale {
  try {
    const v = localStorage.getItem(STORAGE_KEY);
    if (v === 'en' || v === 'pt-BR') return v;
  } catch {
    // no storage: the default
  }
  return 'pt-BR';
}

interface I18n {
  locale: Locale;
  setLocale(l: Locale): void;
  t(key: Key, vars?: Record<string, string | number>): string;
}

const Ctx = createContext<I18n | null>(null);

export function I18nProvider({ children, locale: fixed }: { children: ReactNode; locale?: Locale }) {
  const [locale, setState] = useState<Locale>(fixed ?? initialLocale);
  const setLocale = useCallback((l: Locale) => {
    setState(l);
    try {
      localStorage.setItem(STORAGE_KEY, l);
    } catch {
      // not remembered
    }
    document.documentElement.lang = l;
  }, []);
  const value = useMemo<I18n>(() => ({ locale, setLocale, t: (k, v) => translate(locale, k, v) }), [locale, setLocale]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error('useI18n outside I18nProvider');
  return v;
}
